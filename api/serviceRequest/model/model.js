import mongoose from "mongoose";

const { Schema } = mongoose;

const serviceRequestSchema = new Schema(
  {
    title: {
      type: String,
      required: true,
      trim: true,
      maxlength: 200,
    },
    description: {
      type: String,
      required: true,
      trim: true,
      maxlength: 8000,
    },
    userId: {
      type: Schema.Types.ObjectId,
      ref: "User",
      required: true,
    },
  },
  { timestamps: true }
);

export const ServiceRequest = mongoose.model(
  "ServiceRequest",
  serviceRequestSchema
);
